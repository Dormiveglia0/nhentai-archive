      if(artifacts){await expect(page.locator('.folio-page')).toHaveCSS('opacity','1');await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>undefined)))});await mkdir(artifacts,{recursive:true});await page.addStyleTag({content:'.folio img{filter:blur(32px)!important}'});await page.screenshot({path:artifacts+'/creator-'+width+'.png'});}
      const value = (await (await request.get('/api/subscriptions')).json()).result.find(s=>s.id===subscription.id);
      const newest = value.recent_galleries[0]?.gallery_id;
      expect(newest).toBeTruthy();
      const replay = spawnSync('/opt/nhentai/.venv/bin/python',['-c',"import sqlite3,sys;c=sqlite3.connect(sys.argv[1]);p=(int(sys.argv[2]),int(sys.argv[3]));c.execute('DELETE FROM subscription_seen WHERE subscription_id=? AND gallery_id=?',p);c.execute('DELETE FROM subscription_updates WHERE subscription_id=? AND gallery_id=?',p);c.commit();c.close()",owned+'/data/archive.db',String(subscription.id),String(newest)],{encoding:'utf8'});
      expect(replay.status,replay.stderr).toBe(0);
      expect((await request.post('/api/subscriptions/'+subscription.id+'/check')).ok()).toBe(true);
